"""Small, model-independent helpers for TULIP static-map construction.

The helpers in this module deliberately do not alter TULIP.  They only fuse
the physically observed 16 rings with the 16 rings generated by an existing
16-to-32 checkpoint before those values are converted to a Waymo point cloud.
"""
from __future__ import annotations

from typing import Any

import numpy as np


NATIVE_WIDTH = 2650
MAX_GENERATED_RANGE_M = 75.0
OBSERVED_ROWS = np.arange(0, 32, 2, dtype=np.int64)
GENERATED_ROWS = np.arange(1, 32, 2, dtype=np.int64)


def fuse_16_to_32_observed_generated(
    observed_raw: np.ndarray,
    observed_mask: np.ndarray,
    prediction_raw: np.ndarray,
    *,
    max_generated_range_m: float = MAX_GENERATED_RANGE_M,
) -> tuple[np.ndarray, np.ndarray, dict[str, int]]:
    """Fuse measured 16 rings and a model prediction on a 32-ring grid.

    Inputs are raw-domain arrays. ``observed_raw`` is ``[2,16,2650]`` and
    ``prediction_raw`` is ``[2,32,2650]``.  Even output rows always come from
    measurements and are never range-clipped. Odd rows are used only when range
    is finite and inside ``(0, max_generated_range_m]`` and intensity is finite.
    Out-of-range predictions are removed, not clipped. Negative predicted
    intensity is set to zero because reflectivity is physically non-negative.
    """
    observed = np.asarray(observed_raw, dtype=np.float32)
    mask16 = np.asarray(observed_mask, dtype=bool)
    prediction = np.asarray(prediction_raw, dtype=np.float32)
    if observed.shape != (2, 16, NATIVE_WIDTH):
        raise ValueError(f"observed_raw must be [2,16,{NATIVE_WIDTH}], got {observed.shape}")
    if mask16.shape != (16, NATIVE_WIDTH):
        raise ValueError(f"observed_mask must be [16,{NATIVE_WIDTH}], got {mask16.shape}")
    if prediction.shape != (2, 32, NATIVE_WIDTH):
        raise ValueError(f"prediction_raw must be [2,32,{NATIVE_WIDTH}], got {prediction.shape}")
    if not np.isfinite(max_generated_range_m) or max_generated_range_m <= 0.0:
        raise ValueError("max_generated_range_m must be finite and positive")

    fused = np.zeros((2, 32, NATIVE_WIDTH), dtype=np.float32)
    valid = np.zeros((32, NATIVE_WIDTH), dtype=bool)

    observed_valid = (
        mask16
        & np.isfinite(observed[0])
        & (observed[0] > 0.0)
        & np.isfinite(observed[1])
    )
    fused[:, OBSERVED_ROWS] = observed
    valid[OBSERVED_ROWS] = observed_valid

    generated_range = prediction[0, GENERATED_ROWS]
    generated_range_safe = (
        np.isfinite(generated_range)
        & (generated_range > 0.0)
        & (generated_range <= max_generated_range_m)
    )
    generated_valid = (
        generated_range_safe
        & np.isfinite(prediction[1, GENERATED_ROWS])
    )
    fused[:, GENERATED_ROWS] = prediction[:, GENERATED_ROWS]
    fused[1, GENERATED_ROWS] = np.maximum(fused[1, GENERATED_ROWS], 0.0)
    valid[GENERATED_ROWS] = generated_valid
    fused[:, ~valid] = 0.0

    return fused, valid, {
        "observed_valid_pixels": int(observed_valid.sum()),
        "generated_valid_pixels": int(generated_valid.sum()),
        "generated_range_safety_removed_pixels": int((~generated_range_safe).sum()),
        "generated_range_above_max_removed_pixels": int(
            (np.isfinite(generated_range) & (generated_range > max_generated_range_m)).sum()
        ),
        "generated_negative_intensity_clamped": int(
            (generated_valid & (prediction[1, GENERATED_ROWS] < 0.0)).sum()
        ),
    }


def valid_top_pixel_pose_mask(pixel_pose: np.ndarray) -> np.ndarray:
    """Return pixels with a finite, non-origin Waymo TOP world pose.

    Waymo stores a zero six-DoF pose at some pixels without a native return.
    Treating that identity pose as a real world pose creates points near the
    world origin, tens of kilometres from the current frame.
    """
    pose = np.asarray(pixel_pose, dtype=np.float32)
    if pose.shape != (32, NATIVE_WIDTH, 4, 4):
        raise ValueError(
            f"pixel_pose must be [32,{NATIVE_WIDTH},4,4], got {pose.shape}"
        )
    translation = pose[..., :3, 3]
    return np.isfinite(pose).all(axis=(-2, -1)) & np.any(translation != 0.0, axis=-1)


def static_point_mask(
    points_vehicle: np.ndarray,
    labels: Any,
    *,
    vehicle_y_scale: float = 2.5,
    ego_x: tuple[float, float] = (-3.1, 5.0),
    ego_y: tuple[float, float] = (-3.1, 3.1),
    ego_z: tuple[float, float] = (-0.2, 0.2),
) -> np.ndarray:
    """Reproduce the existing map builder's dynamic-label and roof filtering."""
    points = np.asarray(points_vehicle, dtype=np.float32)
    if points.ndim != 2 or points.shape[1] != 3:
        raise ValueError(f"points_vehicle must be [N,3], got {points.shape}")
    keep = np.ones(points.shape[0], dtype=bool)
    if points.shape[0] == 0:
        return keep

    from waymo_open_dataset import label_pb2

    scales = {
        label_pb2.Label.TYPE_VEHICLE: (1.0, float(vehicle_y_scale), 1.0),
        label_pb2.Label.TYPE_PEDESTRIAN: (1.0, 1.0, 1.0),
        label_pb2.Label.TYPE_CYCLIST: (1.0, 1.0, 1.0),
    }
    keep_types = {label_pb2.Label.TYPE_SIGN}
    for label in labels:
        if label.type in keep_types or label.type not in scales:
            continue
        sx, sy, sz = scales[label.type]
        center = np.array(
            [label.box.center_x, label.box.center_y, label.box.center_z], dtype=np.float32
        )
        dimensions = np.array(
            [label.box.length * sx, label.box.width * sy, label.box.height * sz],
            dtype=np.float32,
        )
        cosine, sine = np.cos(label.box.heading), np.sin(label.box.heading)
        rotation = np.array(
            [[cosine, sine, 0.0], [-sine, cosine, 0.0], [0.0, 0.0, 1.0]],
            dtype=np.float32,
        )
        inside = np.all(np.abs((points - center) @ rotation) <= dimensions / 2.0, axis=1)
        keep &= ~inside

    roof = (
        (points[:, 0] > ego_x[0]) & (points[:, 0] < ego_x[1])
        & (points[:, 1] > ego_y[0]) & (points[:, 1] < ego_y[1])
        & (points[:, 2] > ego_z[0]) & (points[:, 2] < ego_z[1])
    )
    keep &= ~roof
    return keep


def vehicle_to_world(points_vehicle: np.ndarray, frame_pose_transform: Any) -> np.ndarray:
    """Transform ``[N,3]`` vehicle points with Waymo's world<-vehicle pose."""
    points = np.asarray(points_vehicle, dtype=np.float32)
    if points.ndim != 2 or points.shape[1] != 3:
        raise ValueError(f"points_vehicle must be [N,3], got {points.shape}")
    transform = np.asarray(frame_pose_transform, dtype=np.float32)
    if transform.size != 16:
        raise ValueError(f"frame pose must contain 16 values, got {transform.size}")
    matrix = transform.reshape(4, 4)
    homogeneous = np.concatenate(
        [points, np.ones((points.shape[0], 1), dtype=np.float32)], axis=1
    )
    return (homogeneous @ matrix.T)[:, :3].astype(np.float32)
